def main() -> None:
    p = argparse.ArgumentParser(description="Generate the FraudShield synthetic dataset.")
    p.add_argument("--n", type=int, default=100_000, help="total transactions")
    p.add_argument(
        "--fraud-rate",
        type=float,
        default=0.02,
        help="fraud prevalence (default 0.02; real card fraud is 0.1-2%%)",
    )
    p.add_argument("--days", type=int, default=180)
    p.add_argument("--end-date", type=str, default="2026-06-30")
    p.add_argument("--seed", type=int, default=SEED)
    p.add_argument("--out-dir", type=Path, default=Path("ml/data"))
    p.add_argument("--tag", type=str, default="")
    p.add_argument("--parquet", action="store_true")
    a = p.parse_args()

    cfg = Config(
        n_transactions=a.n,
        fraud_rate=a.fraud_rate,
        days=a.days,
        end_date=a.end_date,
        seed=a.seed,
        out_dir=a.out_dir,
        tag=a.tag,
        parquet=a.parquet,
    )

    rng = np.random.default_rng(cfg.seed)
    random.seed(cfg.seed)

    end_dt = datetime.fromisoformat(cfg.end_date).replace(tzinfo=timezone.utc)
    end = end_dt.timestamp()
    start = (end_dt - timedelta(days=cfg.days)).timestamp()

    print(f"FraudShield dataset generator  seed={cfg.seed}")
    print(f"  window     {datetime.fromtimestamp(start, timezone.utc).date()} "
          f"-> {end_dt.date()}  ({cfg.days} days)")
    print(f"  target     {cfg.n_transactions:,} transactions @ {cfg.fraud_rate:.2%} fraud")

    if cfg.fraud_rate >= 0.05:
        print(
            "\n  NOTE: a fraud rate of "
            f"{cfg.fraud_rate:.0%} is far above reality (0.1-2%). Precision will look\n"
            "        much better than it would in production, because precision depends\n"
            "        on the base rate. Fine for a demo; label it as such in any results."
        )

    n_fraud = int(cfg.n_transactions * cfg.fraud_rate)
    n_legit = cfg.n_transactions - n_fraud

    print("\n[1/6] building customer population and legitimate clusters")
    customers, cluster_stats = build_customers(cfg, rng, start, end)
    print(f"      {len(customers):,} customers, "
          f"{cluster_stats['families']} shared devices "
          f"({cluster_stats['kiosks']} kiosks with 5-9 accounts), "
          f"{cluster_stats['offices']} shared-IP networks")

    print("[2/6] simulating legitimate traffic + edge cases")
    events, per_cust, legit_stats = generate_legit(cfg, rng, customers, start, end, n_legit)
    print(f"      {len(events):,} legitimate events   {legit_stats}")

    print("[3/6] injecting fraud archetypes")
    fraud_events, fraud_stats = generate_fraud(
        cfg, rng, customers, per_cust, start, end, n_fraud
    )
    events.extend(fraud_events)
    print(f"      {len(fraud_events):,} new fraud events   {fraud_stats}")

    # attach true account creation times where we know them
    created = {c.cid: c.created_at for c in customers}
    for e in events:
        # do not clobber creation times the fraud generator set deliberately
        if "created_at" not in e and e["cid"] in created:
            e["created_at"] = created[e["cid"]]

    print("[4/6] forward feature pass (chronological, no lookahead)")
    df = compute_features(events, {c.cid: c.segment for c in customers})

    print("[5/6] temporal split + sanity checks")
    bounds = add_split(df, cfg)
    report = sanity_report(df)

    print("[6/6] promo redemption dataset")
    promo = generate_promo(cfg, rng, customers, start, end)
    n = len(promo)
    i_tr, i_va = int(n * 0.70), int(n * 0.85)
    sp = np.array(["train"] * n, dtype=object)
    sp[i_tr:i_va] = "validation"
    sp[i_va:] = "test"
    promo["split"] = sp

    cfg.out_dir.mkdir(parents=True, exist_ok=True)
    suffix = f"_{cfg.tag}" if cfg.tag else ""
    tx_path = cfg.out_dir / f"transactions{suffix}.csv"
    pr_path = cfg.out_dir / f"promo_redemptions{suffix}.csv"
    md_path = cfg.out_dir / f"metadata{suffix}.json"

    df.to_csv(tx_path, index=False)
    promo.to_csv(pr_path, index=False)
    if cfg.parquet:
        df.to_parquet(cfg.out_dir / f"transactions{suffix}.parquet", index=False)

    meta = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "seed": cfg.seed,
        "config": {
            "n_transactions": cfg.n_transactions,
            "fraud_rate_requested": cfg.fraud_rate,
            "days": cfg.days,
            "end_date": cfg.end_date,
        },
        "transactions": {
            "rows": int(len(df)),
            "customers": int(df.customer_id.nunique()),
            "devices": int(df.device_fp.nunique()),
            "ips": int(df.ip_hash.nunique()),
            "fraud_rate_actual": round(float(df.fraud_label.mean()), 5),
            "split_boundaries": bounds,
            **report,
        },
        "promo_redemptions": {
            "rows": int(len(promo)),
            "abuse_rate": round(float(promo.abuse_label.mean()), 5),
        },
        "features": FEATURES,
        "notes": [
            "Features are computed in a single chronological pass using only "
            "pre-event state. No row can see its own outcome or any later event.",
            "first_party_abuse rows are genuinely normal transactions and are "
            "not detectable at payment time. They cap achievable recall.",
            "Synthetic data. Real-world performance will be worse.",
        ],
    }
    md_path.write_text(json.dumps(meta, indent=2))

    # ------------------------------------------------------------------
    print("\n" + "=" * 68)
    print(f"  rows            {len(df):,}")
    print(f"  fraud           {int(df.fraud_label.sum()):,} "
          f"({df.fraud_label.mean():.2%})")
    print(f"  customers       {df.customer_id.nunique():,}")
    print(f"  devices         {df.device_fp.nunique():,}")
    print(f"  split           " + "  ".join(
        f"{k}={v:,}" for k, v in report["rows_by_split"].items()))
    print(f"  train ends      {bounds['train_end'][:10]}")
    print(f"  val ends        {bounds['validation_end'][:10]}")
    print("\n  fraud by type")
    for k, v in report["fraud_type_counts"].items():
        print(f"    {k:<22} {v:,}")
    print("\n  strongest single features (AUC; >0.90 means too easy)")
    for k, v in report["single_feature_auc_top8"].items():
        print(f"    {k:<26} {v:.3f}")
    print(f"\n  fraud that simple rules cannot separate: "
          f"{report['fraud_indistinguishable_by_simple_rules']:.1%}")

    if report["warnings"]:
        print("\n  WARNINGS")
        for w in report["warnings"]:
            print(f"    - {w}")
    else:
        print("\n  no single feature dominates -- the model has to do real work.")

    print("\n  wrote")
    print(f"    {tx_path}")
    print(f"    {pr_path}")
    print(f"    {md_path}")
    print("=" * 68)


if __name__ == "__main__":
    main()
