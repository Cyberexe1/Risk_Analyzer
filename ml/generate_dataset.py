SEED = 20260822

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

PAYMENT_METHODS = ["upi", "card", "netbanking", "wallet", "cod"]
METHOD_WEIGHTS = [0.45, 0.25, 0.08, 0.10, 0.12]  # rough Indian e-commerce mix

# Global prior used for amount_ratio on a customer's first transaction, when no
# baseline exists yet. A production scorer has the same problem and needs the same
# fallback, so the model should learn to distrust amount_ratio when prev_txn_count
# is 0 rather than us quietly imputing a leaky per-customer value.
GLOBAL_AMOUNT_PRIOR = 1500.0

FRAUD_MIX = {
    "card_testing": 0.30,
    "account_takeover": 0.24,
    "ring_cashout": 0.21,
    "refund_abuse": 0.13,
    "first_party_abuse": 0.12,
}

SEGMENTS = {
    #                 share  avg_amount range      txns/day range   sigma
    "regular": (0.58, (400, 3000), (0.05, 0.45), 0.55),
    "budget": (0.15, (120, 600), (0.04, 0.30), 0.45),
    "whale": (0.05, (6000, 40000), (0.03, 0.35), 0.70),
    "family_shared": (0.08, (500, 4000), (0.06, 0.40), 0.60),
    "office_ip": (0.09, (300, 2500), (0.05, 0.35), 0.55),
    "burst_shopper": (0.05, (400, 3500), (0.10, 0.50), 0.65),
}


@dataclass
class Config:
    n_transactions: int = 100_000
    fraud_rate: float = 0.02
    days: int = 180
    end_date: str = "2026-06-30"
    seed: int = SEED
    out_dir: Path = Path("ml/data")
    tag: str = ""
    train_frac: float = 0.70
    val_frac: float = 0.15
    parquet: bool = False


