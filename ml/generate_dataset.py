# Weekly seasonality (Mon..Sun) and a mild month-end payday bump
WEEKDAY_W = np.array([1.00, 0.97, 0.99, 1.03, 1.18, 1.22, 1.05])


def _sample_timestamps(rng, c: Customer, n: int, lo: float, hi: float) -> np.ndarray:
    """Arrival times with weekly seasonality and per-customer hour-of-day habit."""
    if n <= 0:
        return np.array([])
    span_days = max(1.0, (hi - lo) / 86400.0)
    day_idx = np.arange(int(span_days))
    dow = (
        np.array(
            [
                datetime.fromtimestamp(lo + d * 86400, tz=timezone.utc).weekday()
                for d in day_idx
            ]
        )
        if len(day_idx)
        else np.array([0])
    )
    w = WEEKDAY_W[dow]
    # month-end bump
    dom = np.array(
        [datetime.fromtimestamp(lo + d * 86400, tz=timezone.utc).day for d in day_idx]
    )
    w = w * np.where(dom >= 28, 1.15, 1.0)
    w = w / w.sum()

    days = rng.choice(len(day_idx), size=n, p=w)
    hours = np.array([_circular_hour(rng, c.hour_mu, c.hour_kappa) for _ in range(n)])
    ts = lo + days * 86400.0 + hours * 3600.0
    ts = np.clip(ts, lo, hi)
    return np.sort(ts)


def generate_legit(cfg, rng, customers, start, end, target):
    """Generate legitimate events, then inject legitimate edge cases."""
    # Scale rates so the population produces roughly `target` events.
    expected = 0.0
    for c in customers:
        active = max(0.0, end - max(start, c.created_at)) / 86400.0
        expected += c.daily_rate * active
    scale = target / max(1.0, expected)

    events = []
    per_cust = defaultdict(list)

    for c in customers:
        lo = max(start, c.created_at)
        if end - lo < 3600:
            continue
        active_days = (end - lo) / 86400.0
        n = int(rng.poisson(c.daily_rate * scale * active_days))
        if n == 0:
            continue
        ts = _sample_timestamps(rng, c, n, lo, end)
        amounts = rng.lognormal(math.log(c.avg_amount), c.sigma, size=n)
        methods = rng.choice(len(PAYMENT_METHODS), size=n, p=c.method_p)

        dev_pick = rng.choice(len(c.devices), size=n, p=c.device_p)
        # ~2.5% of events come from a fingerprint never seen before: new phone,
        # browser update, cleared storage, incognito. This is the honest base rate
        # of `is_new_device` firing on a completely legitimate customer.
        fresh = rng.random(n) < 0.025

        for j, (t, amt, mi) in enumerate(zip(ts, amounts, methods)):
            failed = rng.random() < c.fail_prone
            device = (
                f"dev_fresh_{c.cid}_{j}" if fresh[j] else c.devices[int(dev_pick[j])]
            )
            ev = {
                "ts": float(t),
                "cid": c.cid,
                "amount": round(float(amt), 2),
                "method": PAYMENT_METHODS[int(mi)],
                "device": device,
                "ip": c.home_ip,
                "status": "failed" if failed else "success",
                "label": 0,
                "fraud_type": "",
            }
            events.append(ev)
            per_cust[c.cid].append(ev)

    stats = _inject_legit_edge_cases(rng, customers, per_cust, events, start, end)
    return events, per_cust, stats


def _inject_legit_edge_cases(rng, customers, per_cust, events, start, end):
    """Legitimate behaviour that looks exactly like fraud. This is what keeps
    precision honest -- remove this function and every metric jumps."""
    by_id = {c.cid: c for c in customers}
    stats = defaultdict(int)

    # 1) Sale-day binge: 4-9 real purchases inside 10 minutes.
    #    Fires the velocity rule with a completely legitimate customer.
    for c in customers:
        if c.segment != "burst_shopper":
            continue
        evs = per_cust.get(c.cid, [])
        if len(evs) < 8:
            continue
        for _ in range(int(rng.integers(1, 4))):
            k = int(rng.integers(4, 10))
            i = int(rng.integers(0, max(1, len(evs) - k)))
            anchor = evs[i]["ts"]
            for j in range(k):
                if i + j < len(evs):
                    evs[i + j]["ts"] = anchor + j * float(rng.uniform(15, 110))
            stats["burst_episodes"] += 1

    # 2) Expired-card retry cascade: 3-6 consecutive genuine failures, then a
    #    success on a different method. Fires the failure-spike rule.
    for c in rng.choice(customers, size=max(1, len(customers) // 22), replace=False):
        evs = per_cust.get(c.cid, [])
        if len(evs) < 10:
            continue
        i = int(rng.integers(0, len(evs) - 7))
        anchor = evs[i]["ts"]
        k = int(rng.integers(3, 7))
        for j in range(k):
            evs[i + j]["ts"] = anchor + j * float(rng.uniform(20, 90))
            evs[i + j]["status"] = "failed"
            evs[i + j]["method"] = "card"
        evs[i + k]["ts"] = anchor + k * 60 + 45
        evs[i + k]["status"] = "success"
        evs[i + k]["method"] = "upi"  # switched method after card kept failing
        stats["failure_cascades"] += 1

    # 3) Travel: new device, new IP, shifted hours, for a few days.
    #    Fires new_device + hour_deviation on a long-standing good customer.
    for c in rng.choice(customers, size=max(1, len(customers) // 16), replace=False):
        evs = per_cust.get(c.cid, [])
        if len(evs) < 12:
            continue
        i = int(rng.integers(0, len(evs) - 5))
        dev = f"dev_travel_{c.cid}"
        ipa = f"ip_travel_{c.cid}"
        for j in range(int(rng.integers(2, 6))):
            if i + j >= len(evs):
                break
            evs[i + j]["device"] = dev
            evs[i + j]["ip"] = ipa
            evs[i + j]["ts"] += float(rng.uniform(-6, 6)) * 3600
        stats["travel_episodes"] += 1

    # 4) Genuine large purchase: 8-20x the customer's own baseline. A phone, a
    #    fridge, a flight. Directly overlaps the amount-anomaly rule.
    for c in rng.choice(customers, size=max(1, len(customers) // 12), replace=False):
        evs = per_cust.get(c.cid, [])
        if len(evs) < 6:
            continue
        e = evs[int(rng.integers(3, len(evs)))]
        e["amount"] = round(c.avg_amount * float(rng.uniform(8, 20)), 2)
        stats["big_ticket"] += 1

    # 5) New account, immediate legitimate high-value first purchase.
    #    Fires new_account + new_device + amount prior mismatch, all innocent.
    newish = [c for c in customers if c.created_at > start]
    for c in rng.choice(newish, size=max(1, len(newish) // 8), replace=False) if newish else []:
        evs = per_cust.get(c.cid, [])
        if not evs:
            continue
        evs[0]["amount"] = round(c.avg_amount * float(rng.uniform(4, 12)), 2)
        evs[0]["ts"] = c.created_at + float(rng.uniform(120, 5400))
        stats["new_acct_bigfirst"] += 1

    return dict(stats)


