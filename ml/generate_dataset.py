"""
FraudShield synthetic dataset generator.

Design principles, in priority order:

1. NO LEAKAGE. Raw events are simulated in chronological order, then features are
   computed in a single forward pass using only state observed strictly BEFORE each
   event. A row's `customer_avg_amount` never includes the row's own amount, and
   never includes anything that happened after it. This is the same code path the
   online scorer would use, which is the point.

2. LABELS ARE NOT A FUNCTION OF FEATURES. If fraud were `amount > 10000`, a model
   would score 1.0 and mean nothing. Fraud here is generated by *behaviour*, and
   legitimate customers deliberately produce the same feature values sometimes
   (see hard negatives). Overlap is the whole point.

3. HARD NEGATIVES ARE MANDATORY. Family-shared tablets, office NAT ranges, sale-day
   binge shoppers, expired-card retry cascades, travelling customers, whales making
   large-but-normal purchases. Without these, device_account_count and amount_ratio
   become nearly perfect separators and the metrics are fiction.

4. ONE ARCHETYPE IS INTENTIONALLY UNDETECTABLE. first_party_abuse relabels genuinely
   normal transactions. It caps achievable recall, which is honest: a real customer
   who buys a real product and later lies about delivery leaves no signal at payment.

Usage
-----
    python ml/generate_dataset.py                       # 100k rows, 2% fraud
    python ml/generate_dataset.py --n 100000 --fraud-rate 0.02
    python ml/generate_dataset.py --n 20000             # fast dev loop
    python ml/generate_dataset.py --fraud-rate 0.10 --tag demo

Outputs to ml/data/:
    transactions.csv        22 features + ids + label + split
    promo_redemptions.csv   7 features + label + split
    metadata.json           config, split boundaries, sanity report
"""

