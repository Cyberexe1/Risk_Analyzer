class RunningHour:
    """Circular running mean of hour-of-day, plus mean absolute deviation.

    Approximate: the MAD is accumulated against a moving mean rather than
    recomputed, which is what an online scorer would do anyway.
    """

    __slots__ = ("s", "c", "n", "mad")

    def __init__(self):
        self.s = 0.0
        self.c = 0.0
        self.n = 0
        self.mad = 0.0

    def mean_hour(self) -> float:
        if self.n == 0:
            return 12.0
        ang = math.atan2(self.s / self.n, self.c / self.n)
        return (ang * 24 / (2 * math.pi)) % 24.0

    def deviation(self, hour: float) -> float:
        if self.n < 5:
            return 0.0
        d = abs(hour - self.mean_hour())
        d = min(d, 24 - d)
        return d / max(1.0, self.mad)

    def update(self, hour: float) -> None:
        d = abs(hour - self.mean_hour())
        d = min(d, 24 - d)
        ang = hour * 2 * math.pi / 24
        self.s += math.sin(ang)
        self.c += math.cos(ang)
        self.n += 1
        self.mad += (d - self.mad) / self.n


def _trim(dq: deque, now: float, window: float) -> int:
    while dq and now - dq[0] > window:
        dq.popleft()
    return len(dq)


def compute_features(events: list[dict], segments: dict | None = None) -> pd.DataFrame:
    """Single chronological pass. Features are read from state BEFORE the event is
    applied, so no row can see its own outcome or anything later.
    """
    events.sort(key=lambda e: e["ts"])

    cust_n = defaultdict(int)
    cust_fail = defaultdict(int)
    cust_sum = defaultdict(float)
    cust_last = {}
    cust_devices = defaultdict(set)
    cust_methods = defaultdict(set)
    cust_first_seen = {}
    hourstate = defaultdict(RunningHour)

    attempts_10m = defaultdict(deque)
    attempts_1h = defaultdict(deque)
    fails_10m = defaultdict(deque)
    fails_1h = defaultdict(deque)

    dev_accounts = defaultdict(set)
    dev_n = defaultdict(int)
    dev_fail = defaultdict(int)
    ip_accounts = defaultdict(set)
    ip_n = defaultdict(int)

    rows = []
    for i, e in enumerate(events):
        cid, ts = e["cid"], e["ts"]
        dev, ipa = e["device"], e["ip"]
        dt = datetime.fromtimestamp(ts, tz=timezone.utc)
        hour = dt.hour + dt.minute / 60.0

        if cid not in cust_first_seen:
            cust_first_seen[cid] = ts

        n_prev = cust_n[cid]
        prior_avg = (cust_sum[cid] / n_prev) if n_prev else GLOBAL_AMOUNT_PRIOR

        v10 = _trim(attempts_10m[cid], ts, 600)
        v1h = _trim(attempts_1h[cid], ts, 3600)
        f10 = _trim(fails_10m[cid], ts, 600)
        f1h = _trim(fails_1h[cid], ts, 3600)

        # account_age uses the account's own creation time; for synthetic fraud
        # accounts with no profile we fall back to first-seen, which is what a
        # real system would have.
        created = e.get("created_at", cust_first_seen[cid])
        age_h = max(0.0, (ts - created) / 3600.0)

        rows.append(
            {
                "transaction_id": f"TX_{i:07d}",
                "customer_id": cid,
                "timestamp": dt.isoformat(),
                "ts_epoch": ts,
                # Emitted so the online scorer can be seeded with the same signup
                # time the offline pass used. Without it, tests must back-compute
                # created_at from a rounded age and inherit that rounding error.
                # NOT a model feature -- see LEAKY_OR_ID in ml/features.py.
                "account_created_at": created,
                "device_fp": dev,
                "ip_hash": ipa,
                # --- transaction (4)
                "amount": e["amount"],
                "payment_method": e["method"],
                "transaction_hour": dt.hour,
                "is_weekend": int(dt.weekday() >= 5),
                # --- velocity (4)
                "txn_count_10m": v10,
                "txn_count_1h": v1h,
                "failed_count_10m": f10,
                "failed_count_1h": f1h,
                # --- customer baseline (5)
                "account_age_hours": round(age_h, 3),
                "customer_avg_amount": round(prior_avg, 2),
                "amount_ratio": round(min(50.0, e["amount"] / max(1.0, prior_avg)), 4),
                "prev_txn_count": n_prev,
                "historical_failure_rate": round(
                    (cust_fail[cid] + 1) / (n_prev + 2), 4
                ),  # Laplace smoothed
                # --- device / ip (5)
                "device_account_count": len(dev_accounts[dev]),
                "device_txn_count": dev_n[dev],
                "device_failure_rate": round((dev_fail[dev] + 1) / (dev_n[dev] + 2), 4),
                "ip_account_count": len(ip_accounts[ipa]),
                "ip_txn_count": ip_n[ipa],
                # --- behavioural (4)
                "is_new_device": int(dev not in cust_devices[cid]),
                "is_new_payment_method": int(e["method"] not in cust_methods[cid]),
                "seconds_since_last_txn": round(
                    ts - cust_last[cid] if cid in cust_last else 999999.0, 1
                ),
                "hour_deviation": round(hourstate[cid].deviation(hour), 4),
                # --- outcome
                "status": e["status"],
                "fraud_label": e["label"],
                "fraud_type": e["fraud_type"],
                # --- metadata for slice analysis ONLY, never a model feature
                "segment": (segments or {}).get(cid, "unknown"),
            }
        )

        # ---- now apply the event to state (strictly after feature read) ----
        failed = e["status"] == "failed"
        cust_n[cid] += 1
        cust_sum[cid] += e["amount"]
        if failed:
            cust_fail[cid] += 1
        cust_last[cid] = ts
        cust_devices[cid].add(dev)
        cust_methods[cid].add(e["method"])
        hourstate[cid].update(hour)

        attempts_10m[cid].append(ts)
        attempts_1h[cid].append(ts)
        if failed:
            fails_10m[cid].append(ts)
            fails_1h[cid].append(ts)

        dev_accounts[dev].add(cid)
        dev_n[dev] += 1
        if failed:
            dev_fail[dev] += 1
        ip_accounts[ipa].add(cid)
        ip_n[ipa] += 1

    return pd.DataFrame(rows)


