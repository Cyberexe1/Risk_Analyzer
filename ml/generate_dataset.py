@dataclass
class Customer:
    cid: str
    created_at: float
    segment: str
    avg_amount: float
    sigma: float
    daily_rate: float
    hour_mu: float
    hour_kappa: float
    methods: list
    method_p: list
    home_device: str
    home_ip: str
    fail_prone: float
    payout: str
    devices: list = field(default_factory=list)
    device_p: list = field(default_factory=list)


def _circular_hour(rng: np.random.Generator, mu: float, kappa: float) -> float:
    """Sample an hour of day from a von Mises distribution wrapped to [0, 24)."""
    angle = rng.vonmises(mu * 2 * math.pi / 24 - math.pi, kappa)
    return ((angle + math.pi) * 24 / (2 * math.pi)) % 24.0


def build_customers(cfg: Config, rng: np.random.Generator, start: float, end: float):
    """Create the customer population, then form legitimate shared-entity clusters."""
    # ~1 customer per 22 transactions gives a realistic history depth per account
    n_customers = max(500, cfg.n_transactions // 22)

    names = list(SEGMENTS)
    shares = np.array([SEGMENTS[s][0] for s in names], dtype=float)
    shares /= shares.sum()

    customers: list[Customer] = []
    for i in range(n_customers):
        seg = names[int(rng.choice(len(names), p=shares))]
        _, (lo, hi), (rlo, rhi), sigma = SEGMENTS[seg]

        # Account age: most accounts predate the window, a meaningful minority are
        # created inside it. The 0-24h band is where account_age carries signal.
        if rng.random() < 0.22:
            created = float(rng.uniform(start, end - 3600))
        else:
            created = float(rng.uniform(start - 3 * 365 * 86400, start))

        customers.append(
            Customer(
                cid=f"CUST_{i:06d}",
                created_at=created,
                segment=seg,
                avg_amount=float(rng.uniform(lo, hi)),
                sigma=sigma,
                daily_rate=float(rng.uniform(rlo, rhi)),
                hour_mu=float(rng.uniform(8, 23)),
                hour_kappa=float(rng.uniform(1.5, 6.0)),
                methods=PAYMENT_METHODS,
                method_p=list(
                    np.array(METHOD_WEIGHTS) * rng.uniform(0.5, 1.5, len(PAYMENT_METHODS))
                ),
                home_device=f"dev_{i:06d}",
                home_ip=f"ip_{i:06d}",
                fail_prone=float(rng.beta(1.4, 30.0)),
                payout=f"payout_{i:06d}",
            )
        )

    for c in customers:
        p = np.array(c.method_p, dtype=float)
        c.method_p = list(p / p.sum())

    # Real people own several devices: a phone, a laptop, a work machine, a tablet.
    # An earlier version gave every customer exactly one device, which made
    # `is_new_device` a near-perfect fraud tell (gain 2163, PR-AUC 0.92) purely as
    # a generator artefact. Device loyalty has to be realistic or that one feature
    # does all the work.
    for i, c in enumerate(customers):
        k = int(rng.choice([1, 2, 3, 4], p=[0.22, 0.40, 0.26, 0.12]))
        extra = [f"dev_{i:06d}_x{j}" for j in range(1, k)]
        c.devices = [c.home_device] + extra
        w = np.array([0.62] + list(rng.uniform(0.08, 0.30, len(extra))))
        c.device_p = list(w / w.sum())

    # --- Hard negative cluster 1: family-shared devices -------------------
    # 2-4 real accounts on one physical tablet. Produces legitimate
    # device_account_count of 2-4, directly overlapping the device-abuse rule.
    fam = [c for c in customers if c.segment == "family_shared"]
    rng.shuffle(fam)
    i = 0
    families = 0
    kiosks = 0
    while i < len(fam) - 1:
        # ~18% of clusters are a shared kiosk, phone-shop counter or internet
        # cafe: 5-9 unrelated but genuine accounts on one device. Without these,
        # "device_account_count > 4" becomes a flawless separator and the device
        # rule reports perfect precision it would never achieve in production.
        if rng.random() < 0.18:
            k = int(rng.integers(5, 10))
            kiosk = True
        else:
            k = int(rng.integers(2, 5))
            kiosk = False
        group = fam[i : i + k]
        if len(group) < 2:
            break
        shared = group[0].home_device
        shared_ip = group[0].home_ip
        for c in group:
            c.home_device = shared
            # kiosk users are strangers passing through, not one household on
            # one router, so they keep their own IPs
            if not kiosk:
                c.home_ip = shared_ip
        families += 1
        kiosks += int(kiosk)
        i += k

    # --- Hard negative cluster 2: office / campus / CGNAT IPs -------------
    # 8-40 unrelated accounts behind one egress IP. This is the single largest
    # false-positive source for IP-based rules in production.
    off = [c for c in customers if c.segment == "office_ip"]
    rng.shuffle(off)
    i = 0
    offices = 0
    while i < len(off) - 1:
        k = int(rng.integers(8, 41))
        group = off[i : i + k]
        if len(group) < 4:
            break
        shared_ip = group[0].home_ip
        for c in group:
            c.home_ip = shared_ip
        offices += 1
        i += k

    return customers, {"families": families, "kiosks": kiosks, "offices": offices}


