def _email_similarity(rng, abusive: bool) -> float:
    """Normalised edit-distance similarity to other accounts in the cluster.
    Abusers reuse a stem (ravi+1@, ravi.k2@); real customers mostly do not.
    Overlap is deliberate: some families genuinely use ravi1@/ravi2@.
    """
    return float(np.clip(rng.beta(5, 2) if abusive else rng.beta(1.6, 6), 0, 1))


def generate_promo(cfg, rng, customers, start, end):
    """Promo abuse is scored at redemption, not at checkout: by the time a payment
    is scored the cashback is already credited. Different population, different
    base rate (~7-8% vs ~2%), so it is evaluated separately.
    """
    n_legit = max(200, int(cfg.n_transactions * 0.055))
    n_abuse = int(n_legit * 0.081 / (1 - 0.081))
    rows = []

    pool = [c for c in customers if c.created_at > start - 30 * 86400]
    if len(pool) < 50:
        pool = customers

    # --- legitimate redemptions ---
    for i in range(n_legit):
        c = pool[int(rng.integers(0, len(pool)))]
        ts = float(rng.uniform(max(start, c.created_at), end))
        # Family/office clusters make some legit rows look clustered -- on purpose.
        on_dev = int(rng.integers(0, 2)) if c.segment == "family_shared" else 0
        acc_dev_7d = (
            int(rng.integers(1, 4)) if c.segment == "family_shared" else 1
        )
        on_ip = int(rng.integers(0, 3)) if c.segment == "office_ip" else 0
        comp = (
            int(rng.integers(8, 41))
            if c.segment == "office_ip"
            else (int(rng.integers(2, 5)) if c.segment == "family_shared" else 1)
        )
        rows.append(
            {
                "redemption_id": f"RD_{i:06d}",
                "customer_id": c.cid,
                "ts_epoch": ts,
                "timestamp": datetime.fromtimestamp(ts, tz=timezone.utc).isoformat(),
                "promo_redemptions_on_device": on_dev,
                "promo_redemptions_on_ip": on_ip,
                "accounts_on_device_7d": acc_dev_7d,
                # real people browse before claiming
                "signup_to_redeem_seconds": round(float(rng.lognormal(7.6, 1.5)), 1),
                "email_pattern_similarity": _email_similarity(rng, False),
                "component_account_count": comp,
                "payout_destination_reuse": 0,
                "abuse_label": 0,
            }
        )

    # --- abusive redemptions: clusters claiming one offer repeatedly ---
    made = 0
    cl = 0
    while made < n_abuse:
        k = int(rng.integers(3, 9))
        t0 = float(rng.uniform(start, end - 86400))
        # Sloppier operators reuse the payout destination; better ones rotate it.
        reuses_payout = rng.random() < 0.62
        for a in range(k):
            if made >= n_abuse:
                break
            rows.append(
                {
                    "redemption_id": f"RD_AB_{cl:05d}_{a:02d}",
                    "customer_id": f"CUST_PA{cl:05d}_{a:02d}",
                    "ts_epoch": t0 + a * float(rng.uniform(60, 5400)),
                    "timestamp": datetime.fromtimestamp(
                        t0 + a * float(rng.uniform(60, 5400)), tz=timezone.utc
                    ).isoformat(),
                    "promo_redemptions_on_device": a if rng.random() < 0.75 else 0,
                    "promo_redemptions_on_ip": a,
                    "accounts_on_device_7d": min(k, a + 1) if rng.random() < 0.8 else 1,
                    # scripted signups redeem almost immediately
                    "signup_to_redeem_seconds": round(float(rng.lognormal(3.4, 1.1)), 1),
                    "email_pattern_similarity": _email_similarity(rng, True),
                    "component_account_count": k,
                    "payout_destination_reuse": int(reuses_payout and a > 0),
                    "abuse_label": 1,
                }
            )
            made += 1
        cl += 1

    df = pd.DataFrame(rows).sort_values("ts_epoch").reset_index(drop=True)
    return df


