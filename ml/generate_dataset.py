def generate_fraud(cfg, rng, customers, per_cust, start, end, n_fraud):
    """Produce fraud events per archetype until each quota is met.

    Every archetype is generated from behaviour, never by setting a feature value
    directly. `first_party_abuse` produces no anomalous behaviour at all.
    """
    quotas = {k: int(round(n_fraud * v)) for k, v in FRAUD_MIX.items()}
    out: list[dict] = []
    stats = defaultdict(int)
    by_id = {c.cid: c for c in customers}
    ring_id = 0

    # Per-customer sorted event times, so a victim can be picked by TIME rather
    # than by history depth. Selecting "customers with >= 15 events" and then
    # anchoring inside their history pushed account takeover and refund abuse
    # toward the end of the window -- 37% of all fraud landed late, and the
    # validation split ended up at 3.07% fraud against 1.73% in train. Base rate
    # differences across splits move PR-AUC on their own, which makes the metric
    # unreadable.
    times = {cid: np.array([e["ts"] for e in evs]) for cid, evs in per_cust.items()}
    cid_list = [c for c in times if len(times[c]) >= 12]

    def pick_victim(min_history: int = 10):
        """Uniform in TIME first, then find an account with enough prior history."""
        for _ in range(60):
            t = float(rng.uniform(start + 20 * 86400, end - 86400))
            cid = cid_list[int(rng.integers(0, len(cid_list)))]
            if int(np.searchsorted(times[cid], t)) >= min_history:
                return by_id.get(cid), t
        return None, None

    # --- Card testing -----------------------------------------------------
    # Working through a list of stolen credentials. High volume, tight window,
    # mostly declines, small amounts to avoid triggering issuer limits.
    produced = 0
    ep = 0
    while produced < quotas["card_testing"]:
        device = f"dev_ct_{ep:05d}"
        ipa = f"ip_ct_{ep // 3:05d}"  # a few episodes share infrastructure
        cid = f"CUST_CT_{ep:05d}"
        t0 = float(rng.uniform(start + 86400, end - 86400))
        # ~30% are dormant "sleeper" accounts aged deliberately before use, which
        # is exactly how operators defeat a naive account-age rule. Without these,
        # account_age_hours alone separates fraud far too well.
        if rng.random() < 0.30:
            acct_created = t0 - float(rng.uniform(30, 400)) * 86400
        else:
            acct_created = t0 - float(rng.uniform(300, 172800))
        n = int(rng.integers(6, 26))
        window = float(rng.uniform(240, 1500))
        for j in range(n):
            # ~72% decline rate is the signature: they are guessing.
            failed = rng.random() < 0.72
            out.append(
                {
                    "ts": t0 + j * (window / n) + float(rng.uniform(-4, 4)),
                    "cid": cid,
                    "amount": round(float(rng.uniform(30, 900)), 2),
                    "method": "card",
                    "device": device,
                    "ip": ipa,
                    "status": "failed" if failed else "success",
                    "label": 1,
                    "fraud_type": "card_testing",
                    "created_at": acct_created,
                }
            )
        produced += n
        ep += 1
        stats["card_testing_episodes"] += 1

    # --- Account takeover -------------------------------------------------
    # Real account, stolen credentials. New device, unusual hour, amount well
    # above the victim's own baseline. Detectable mainly via amount_ratio.
    produced = 0
    guard = 0
    while produced < quotas["account_takeover"] and cid_list and guard < 100000:
        guard += 1
        c, anchor = pick_victim(12)
        if c is None:
            continue
        device = f"dev_ato_{c.cid}"
        ipa = f"ip_ato_{c.cid}"
        n = int(rng.integers(1, 5))
        # Off-hours relative to THIS customer, not an absolute "3am is bad" rule
        hour_shift = float(rng.uniform(6, 14)) * 3600
        for j in range(n):
            out.append(
                {
                    "ts": min(end - 60, anchor + hour_shift + j * float(rng.uniform(60, 900))),
                    "cid": c.cid,
                    "amount": round(c.avg_amount * float(rng.uniform(3.5, 15.0)), 2),
                    "method": rng.choice(["card", "netbanking", "wallet"]),
                    "device": device,
                    "ip": ipa,
                    "status": "failed" if rng.random() < 0.25 else "success",
                    "label": 1,
                    "fraud_type": "account_takeover",
                    "created_at": c.created_at,
                }
            )
        produced += n
        stats["ato_episodes"] += 1

    # --- Ring / coordinated cashout ---------------------------------------
    # Several fresh accounts on shared devices and IPs, acting in a loose window.
    # Each account alone is unremarkable; the cluster is the evidence.
    produced = 0
    while produced < quotas["ring_cashout"]:
        n_acct = int(rng.integers(4, 13))
        n_dev = max(1, n_acct // int(rng.integers(2, 5)))
        devices = [f"dev_ring{ring_id:04d}_{d}" for d in range(n_dev)]
        ips = [f"ip_ring{ring_id:04d}_{d}" for d in range(max(1, n_dev // 2))]
        t0 = float(rng.uniform(start + 86400, end - 7 * 86400))
        base = float(rng.uniform(800, 6000))
        # Rings age their mules too: a third of the accounts in a cluster were
        # created well before the cashout window.
        aged = rng.random() < 0.33
        for a in range(n_acct):
            cid = f"CUST_RING{ring_id:04d}_{a:02d}"
            if aged:
                acct_created = t0 - float(rng.uniform(20, 300)) * 86400
            else:
                acct_created = t0 - float(rng.uniform(600, 259200))
            k = int(rng.integers(1, 5))
            for j in range(k):
                out.append(
                    {
                        "ts": t0 + float(rng.uniform(0, 5 * 86400)),
                        "cid": cid,
                        "amount": round(base * float(rng.uniform(0.7, 1.4)), 2),
                        "method": rng.choice(["card", "upi", "wallet"]),
                        "device": devices[int(rng.integers(0, len(devices)))],
                        "ip": ips[int(rng.integers(0, len(ips)))],
                        "status": "failed" if rng.random() < 0.18 else "success",
                        "label": 1,
                        "fraud_type": "ring_cashout",
                        "created_at": acct_created,
                    }
                )
                produced += 1
        ring_id += 1
        stats["rings"] += 1

    # --- Refund / returns abuse -------------------------------------------
    # A serial claimant. Signal at payment time is weak: slightly elevated
    # amounts on a normal-looking account. Most of the evidence is post-purchase.
    produced = 0
    guard = 0
    while produced < quotas["refund_abuse"] and cid_list and guard < 100000:
        guard += 1
        c, anchor = pick_victim(6)
        if c is None:
            continue
        out.append(
            {
                "ts": min(end - 60, anchor + float(rng.uniform(3600, 86400))),
                "cid": c.cid,
                "amount": round(c.avg_amount * float(rng.uniform(1.8, 4.5)), 2),
                "method": rng.choice(["card", "cod", "upi"]),
                "device": c.devices[int(rng.integers(0, len(c.devices)))],
                "ip": c.home_ip,
                "status": "success",
                "label": 1,
                "fraud_type": "refund_abuse",
                "created_at": c.created_at,
            }
        )
        produced += 1
        stats["refund_abuse"] += 1

    # --- First-party ("friendly") fraud -----------------------------------
    # A REAL customer, a REAL purchase, own device, own IP, normal amount. They
    # later falsely claim non-delivery. There is nothing to detect at payment
    # time and we do not pretend otherwise: we relabel existing normal events.
    #
    # This is what caps achievable recall. Any dataset without it reports a
    # recall number that no production system can reach.
    flat = [e for evs in per_cust.values() for e in evs if e["label"] == 0]
    n_fp = quotas["first_party_abuse"]
    if flat and n_fp:
        # Mild bias toward higher-value orders (worth disputing), nothing more.
        amts = np.array([e["amount"] for e in flat])
        w = np.clip(amts / (amts.mean() + 1e-9), 0.3, 4.0)
        w = w / w.sum()
        idx = rng.choice(len(flat), size=min(n_fp, len(flat)), replace=False, p=w)
        for i in idx:
            flat[int(i)]["label"] = 1
            flat[int(i)]["fraud_type"] = "first_party_abuse"
        stats["first_party_abuse"] = len(idx)

    return out, dict(stats)


