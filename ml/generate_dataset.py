def add_split(df: pd.DataFrame, cfg: Config) -> dict:
    """Split by TIME, not randomly. A random split puts a ring's Monday
    transactions in train and its Tuesday transactions in test; the model then
    'detects' a cluster it memorised. We measured ~20pp of inflated ring recall
    from exactly that mistake.
    """
    df.sort_values("ts_epoch", inplace=True)
    df.reset_index(drop=True, inplace=True)
    n = len(df)
    i_tr = int(n * cfg.train_frac)
    i_va = int(n * (cfg.train_frac + cfg.val_frac))
    split = np.array(["train"] * n, dtype=object)
    split[i_tr:i_va] = "validation"
    split[i_va:] = "test"
    df["split"] = split
    return {
        "train_end": df.loc[max(0, i_tr - 1), "timestamp"],
        "validation_end": df.loc[max(0, i_va - 1), "timestamp"],
        "test_end": df.loc[n - 1, "timestamp"],
    }


def single_feature_auc(x: np.ndarray, y: np.ndarray) -> float:
    """Rank-based AUC (Mann-Whitney). Used as a leakage detector: if one raw
    feature separates the classes almost perfectly, the dataset is too easy and
    any downstream metric is meaningless.
    """
    pos, neg = int(y.sum()), int(len(y) - y.sum())
    if pos == 0 or neg == 0:
        return 0.5
    order = np.argsort(x, kind="mergesort")
    ranks = np.empty(len(x), dtype=float)
    ranks[order] = np.arange(1, len(x) + 1)
    # average ranks over ties
    s = pd.Series(x)
    ranks = s.rank(method="average").to_numpy()
    auc = (ranks[y == 1].sum() - pos * (pos + 1) / 2) / (pos * neg)
    return float(max(auc, 1 - auc))


FEATURES = [
    "amount", "transaction_hour", "is_weekend",
    "txn_count_10m", "txn_count_1h", "failed_count_10m", "failed_count_1h",
    "account_age_hours", "customer_avg_amount", "amount_ratio", "prev_txn_count",
    "historical_failure_rate",
    "device_account_count", "device_txn_count", "device_failure_rate",
    "ip_account_count", "ip_txn_count",
    "is_new_device", "is_new_payment_method", "seconds_since_last_txn",
    "hour_deviation",
]


def sanity_report(df: pd.DataFrame) -> dict:
    y = df["fraud_label"].to_numpy()
    aucs = {f: round(single_feature_auc(df[f].to_numpy(float), y), 4) for f in FEATURES}
    top = dict(sorted(aucs.items(), key=lambda kv: -kv[1])[:8])

    warnings = []
    for f, a in aucs.items():
        if a > 0.90:
            warnings.append(
                f"'{f}' alone reaches AUC {a:.3f} -- dataset likely too easy; "
                "add hard negatives that share this feature value."
            )

    # Overlap check: how much of the fraud looks ordinary?
    ordinary = df[
        (df.txn_count_10m <= 2)
        & (df.amount_ratio < 3)
        & (df.device_account_count <= 2)
        & (df.failed_count_1h <= 1)
    ]
    frac_fraud_ordinary = (
        float(ordinary.fraud_label.sum() / max(1, df.fraud_label.sum()))
    )

    return {
        "single_feature_auc_top8": top,
        "warnings": warnings,
        "fraud_indistinguishable_by_simple_rules": round(frac_fraud_ordinary, 4),
        "fraud_rate_by_split": {
            k: round(float(v), 5)
            for k, v in df.groupby("split")["fraud_label"].mean().items()
        },
        "rows_by_split": {k: int(v) for k, v in df["split"].value_counts().items()},
        "fraud_type_counts": {
            k: int(v) for k, v in df[df.fraud_label == 1]["fraud_type"].value_counts().items()
        },
    }


