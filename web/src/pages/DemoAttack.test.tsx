import { render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { api, ApiError, type DemoAttackResult, type DemoStatus } from '../api'
import DemoAttack from './DemoAttack'

/**
 * The demo trigger's console behaviour.
 *
 * Two things matter here and the rest is presentation:
 *
 *   1. The control is not offered when the server says it would refuse, and a
 *      destructive-looking action is never one accidental click away.
 *   2. Every number shown comes from the response. The console must not derive a
 *      score, a decision or a signal — one that recomputed them could disagree
 *      with the queue and the audit trail.
 */

const READY: DemoStatus = {
  enabled: true,
  demo_mode: true,
  provider_is_simulated: true,
  scenario: 'fraud_attack',
  attempts: 8,
  window_seconds: 420,
  blocked_because: [],
}

const OFF: DemoStatus = {
  enabled: false,
  demo_mode: false,
  provider_is_simulated: true,
  scenario: 'fraud_attack',
  attempts: 8,
  window_seconds: 420,
  blocked_because: ['FRAUDSHIELD_DEMO_MODE is not enabled'],
}

function attempt(n: number, score: number, decision: DemoAttackResult['results'][number]['decision']) {
  return {
    attempt: n,
    transaction_id: `pay_demo_${n}`,
    order_id: `ord_demo_${n}`,
    at: `2026-08-29T08:3${n}:00+00:00`,
    amount: 20000 + n * 1000,
    payment_method: 'card',
    settlement: 'failed',
    risk_score: score,
    decision,
    sub_scores: { ml: 100, rules: 35, network: 0 },
    fired_rules: n >= 7 ? ['velocity_breach', 'amount_anomaly'] : ['amount_anomaly'],
    override: null,
    txn_count_10m: n - 1,
    amount_ratio: 8.6,
  }
}

